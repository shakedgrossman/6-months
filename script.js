/* =================================
   STATE
================================= */

let currentMemory = 0;

let isAnimating = false;


/* =================================
   ELEMENTS
================================= */

const opening =
    document.getElementById("opening");

const playButton =
    document.getElementById("playButton");

const timeline =
    document.getElementById("timeline");

const memory =
    document.getElementById("memory");

const memoryImage =
    document.getElementById("memoryImage");

const memoryVideo =
    document.getElementById("memoryVideo");

const memoryTitle =
    document.getElementById("memoryTitle");

const memoryDate =
    document.getElementById("memoryDate");

const memoryDescription =
    document.getElementById("memoryDescription");

const previousButton =
    document.getElementById("previousButton");

const nextButton =
    document.getElementById("nextButton");

const restartButton =
    document.getElementById("restartButton");


/* =================================
   HELPER
================================= */

function isVideo(file) {

    const lower =
        file.toLowerCase();

    return (
        lower.endsWith(".mp4") ||
        lower.endsWith(".mov")
    );

}


/* =================================
   PRELOAD
================================= */

function preloadMemory(index) {

    if (
        index < 0 ||
        index >= memories.length
    ) {
        return;
    }


    const item =
        memories[index];


    if (isVideo(item.file)) {

        const video =
            document.createElement("video");

        video.preload =
            "metadata";

        video.src =
            "Images/" + item.file;

    } else {

        const image =
            new Image();

        image.src =
            "Images/" + item.file;

    }

}


/* =================================
   UPDATE TEXT
================================= */

function updateText(item) {

    memoryTitle.textContent =
        item.title;


    memoryDate.textContent =
        item.date;


    memoryDescription.textContent =
        item.description;


    memoryDate.style.display =
        item.date
            ? "block"
            : "none";


    memoryDescription.style.display =
        item.description
            ? "block"
            : "none";
}


/* =================================
   LOAD MEDIA
================================= */

function loadMedia(item) {

    if (isVideo(item.file)) {

        memoryImage.style.display =
            "none";


        memoryVideo.style.display =
            "block";


        memoryVideo.src =
            "Images/" + item.file;


        memoryVideo.load();

    } else {

        memoryVideo.pause();

        memoryVideo.removeAttribute(
            "src"
        );

        memoryVideo.load();


        memoryVideo.style.display =
            "none";


        memoryImage.style.display =
            "block";


        memoryImage.src =
            "Images/" + item.file;


        memoryImage.alt =
            item.title;
    }

}


/* =================================
   SHOW MEMORY
================================= */

function showMemory(
    index,
    direction = 0,
    animate = false
) {

    if (
        index < 0 ||
        index >= memories.length
    ) {
        return;
    }


    if (
        animate &&
        isAnimating
    ) {
        return;
    }


    const item =
        memories[index];


    /* =============================
       NO ANIMATION
    ============================= */

    if (!animate) {

        currentMemory =
            index;

        loadMedia(item);

        updateText(item);

        updateRestartButton();

        preloadMemory(index + 1);

        return;
    }


    /* =============================
       START ANIMATION
    ============================= */

    isAnimating = true;


    /*
     * Going forward:
     * old → leaves left
     * new → enters from right
     *
     * Going backward:
     * old → leaves right
     * new → enters from left
     */

    const exitDistance =
        direction > 0
            ? "-110vw"
            : "110vw";


    const enterDistance =
        direction > 0
            ? "110vw"
            : "-110vw";


    /* =============================
       EXIT
    ============================= */

    memory.style.transition =
        "transform 0.45s ease, opacity 0.45s ease";


    memory.style.transform =
        `translateX(${exitDistance})`;


    memory.style.opacity =
        "0";


    /* =============================
       CHANGE CONTENT
    ============================= */

    setTimeout(() => {

        currentMemory =
            index;


        loadMedia(item);

        updateText(item);

        updateRestartButton();


        /*
         * Put the new memory
         * on the opposite side.
         */

        memory.style.transition =
            "none";


        memory.style.transform =
            `translateX(${enterDistance})`;


        memory.style.opacity =
            "0";


        /*
         * Force browser to register
         * the new position.
         */

        void memory.offsetWidth;


        /* =============================
           ENTER
        ============================= */

        memory.style.transition =
            "transform 0.55s ease, opacity 0.55s ease";


        memory.style.transform =
            "translateX(0)";


        memory.style.opacity =
            "1";


        setTimeout(() => {

            isAnimating =
                false;

        }, 550);


        /*
         * Preload nearby memories
         */

        preloadMemory(index + 1);

        preloadMemory(index - 1);

    }, 450);

}


/* =================================
   RESTART BUTTON
================================= */

function updateRestartButton() {

    if (
        currentMemory ===
        memories.length - 1
    ) {

        restartButton.classList.add(
            "visible"
        );

    } else {

        restartButton.classList.remove(
            "visible"
        );

    }

}


/* =================================
   PLAY
================================= */

playButton.addEventListener(
    "click",
    () => {

        opening.classList.add(
            "hidden"
        );


        setTimeout(() => {

            timeline.classList.add(
                "active"
            );


            showMemory(
                0,
                0,
                false
            );


        }, 500);

    }
);


/* =================================
   NEXT
================================= */

nextButton.addEventListener(
    "click",
    () => {

        if (
            currentMemory <
            memories.length - 1
        ) {

            showMemory(
                currentMemory + 1,
                1,
                true
            );

        }

    }
);


/* =================================
   PREVIOUS
================================= */

previousButton.addEventListener(
    "click",
    () => {

        if (
            currentMemory > 0
        ) {

            showMemory(
                currentMemory - 1,
                -1,
                true
            );

        }

    }
);


/* =================================
   RESTART
================================= */

restartButton.addEventListener(
    "click",
    () => {

        if (isAnimating) {
            return;
        }


        restartButton.classList.remove(
            "visible"
        );


        showMemory(
            0,
            -1,
            true
        );

    }
);


/* =================================
   KEYBOARD
================================= */

document.addEventListener(
    "keydown",
    (event) => {

        if (event.key === "ArrowRight") {

            if (
                currentMemory <
                memories.length - 1
            ) {

                showMemory(
                    currentMemory + 1,
                    1,
                    true
                );

            }

        }


        if (event.key === "ArrowLeft") {

            if (
                currentMemory > 0
            ) {

                showMemory(
                    currentMemory - 1,
                    -1,
                    true
                );

            }

        }

    }
);
